#!/usr/bin/env node
// gp-answer-key-export.js — export all answers from all RP exams in a printable markdown table
// Useful for Marcus to quickly verify answer correctness across all 11 exams

const fs = require('fs');
const path = require('path');

const DATA_DIR = path.join(__dirname, '..', 'data');
const RP_FILES = fs.readdirSync(DATA_DIR)
  .filter(f => /^retake-practice-\d+\.json$/.test(f))
  .sort();

const OUTPUT_FILE = path.join(__dirname, '..', 'docs', 'agents', 'gp-answer-key-export.md');

const lines = [
  '# GP Answer Key Export',
  '',
  `Generated: ${new Date().toISOString()}`,
  '',
  '> This file is auto-generated by `scripts/gp-answer-key-export.js`.',
  '> Do not edit manually.',
  '',
];

for (const file of RP_FILES) {
  const data = JSON.parse(fs.readFileSync(path.join(DATA_DIR, file), 'utf8'));
  lines.push(`## ${data.title || file}`);
  lines.push('');
  lines.push('| Q# | Standard | Inputs | Answers |');
  lines.push('|----|----------|--------|---------|');
  
  for (const q of data.questions) {
    const inputs = q.inputs || [];
    const answered = inputs.filter(i => i.answer !== undefined && i.answer !== null);
    const unanswered = inputs.filter(i => i.answer === undefined || i.answer === null);
    
    const answerList = answered.map(i => `${i.id}: \`${i.answer}\``).join(', ');
    const missingTag = unanswered.length > 0 ? ` *(${unanswered.length} missing)*` : '';
    
    lines.push(`| Q${q.number} | ${q.standard || '—'} | ${inputs.length} | ${answerList || '—'}${missingTag} |`);
  }
  
  lines.push('');
}

const content = lines.join('\n');
fs.writeFileSync(OUTPUT_FILE, content);
console.log(`gp-answer-key-export: written to ${OUTPUT_FILE}`);
console.log(`  ${RP_FILES.length} exams, ${RP_FILES.reduce((sum, f) => {
  const d = JSON.parse(fs.readFileSync(path.join(DATA_DIR, f), 'utf8'));
  return sum + d.questions.reduce((qs, q) => qs + (q.inputs || []).length, 0);
}, 0)} total inputs`);
